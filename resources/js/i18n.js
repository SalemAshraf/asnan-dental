export const i18n = reactive({ locale: (typeof localStorage !== 'undefined' && localStorage.getItem('locale')) || 'ar' });

function applyDir() {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = i18n.locale;
    document.documentElement.dir = i18n.locale === 'ar' ? 'rtl' : 'ltr';
}

export function setLocale(locale) {
    if (!messages[locale]) return;
    i18n.locale = locale;
    localStorage.setItem('locale', locale);
    applyDir();
}

export function toggleLocale() {
    setLocale(i18n.locale === 'ar' ? 'en' : 'ar');
}

export const intlLocale = () => (i18n.locale === 'ar' ? 'ar-EG' : 'en-GB');
export const fmtDate = (d, opts) => new Date(d).toLocaleDateString(intlLocale(), opts);
export const fmtTime = (d) => new Date(d).toLocaleTimeString(intlLocale(), { hour: '2-digit', minute: '2-digit' });
export const statusLabel = (v) => t('st.' + v);

export function t(key, params) {
    let s = messages[i18n.locale][key] ?? messages.ar[key] ?? key;
    if (params) {
        for (const k of Object.keys(params)) s = s.replaceAll(`{${k}}`, params[k]);
    }
    return s;
}

